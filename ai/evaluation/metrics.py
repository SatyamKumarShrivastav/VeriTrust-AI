"""
VeriTrust AI — Model Evaluation & Performance Metrics
Computes Precision, Recall, F1-Score, and ROC-AUC across benchmark validation sets.
Designed for Semester VII KD evaluation reporting.
"""
from typing import List, Dict, Any


def calculate_evaluation_metrics(
    y_true: List[int],
    y_pred: List[int],
    y_scores: List[float] = None,
) -> Dict[str, Any]:
    """
    Compute binary classification metrics without heavy external dependencies.
    1 = Manipulated / Deepfake
    0 = Genuine / Unmanipulated
    """
    tp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 1)
    tn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 0)
    fp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 1)
    fn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 0)

    total = len(y_true)
    accuracy = (tp + tn) / total if total > 0 else 0.0
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0

    return {
        "total_samples": total,
        "true_positives": tp,
        "true_negatives": tn,
        "false_positives": fp,
        "false_negatives": fn,
        "accuracy": round(accuracy, 4),
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1_score": round(f1, 4),
    }

